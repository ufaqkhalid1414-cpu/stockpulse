export function languageById(id: Lang) {
  return languages.find((language) => language.id === id) ?? languages[0];
}

function isLandingCopyKey(key: CopyKey): key is LandingCopyKey {
  return (LANDING_KEYS as readonly string[]).includes(key);
}

export function t(lang: Lang, key: CopyKey, vars?: Record<string, string | number>) {
  let template = dictionaries[lang][key];
  if (
    lang !== "en" &&
    key.startsWith("landing") &&
    isLandingCopyKey(key) &&
    landingCopy[lang][key] === undefined
  ) {
    if (process.env.NODE_ENV === "development") {
      console.warn(`[i18n] Missing landing copy for "${lang}" key "${key}"; falling back to English.`);
    }
    template = dictionaries.en[key];
  }
  template = template ?? dictionaries.en[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
}
